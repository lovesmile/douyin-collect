function chooseVideoIdeas(rows) {
  const picked = [];
  for (const wanted of ['显白', '猫眼', '高闪', '温柔', '甜酷', '蝴蝶']) {
    const row = rows.find((item) => !picked.includes(item) && `${item.visual_style}${item.content_angle}${item.title}`.includes(wanted));
    if (row) picked.push(row);
    if (picked.length >= 3) break;
  }
  for (const row of rows) {
    if (picked.length >= 3) break;
    if (!picked.includes(row)) picked.push(row);
  }
  return picked;
}

